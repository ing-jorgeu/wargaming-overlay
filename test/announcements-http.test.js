const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const {spawn} = require('node:child_process');
const {once} = require('node:events');
test('HTTP and SSE keep working when optional YouTube authentication fails', {timeout:15000}, async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(),'overlay-toast-http-'));
  const repo = path.resolve(__dirname,'..');
  const preload = path.join(directory,'preload.cjs');
  await fs.writeFile(preload, `
    const http=require('node:http'), original=http.createServer;
    http.createServer=(...args)=>{const server=original(...args);server.on('listening',()=>console.log('TEST_PORT='+server.address().port));return server;};
    require('node:child_process').spawn=()=>{const child=new (require('node:events').EventEmitter)();child.stdout=new (require('node:stream').PassThrough)();child.kill=()=>{};return child;};
    require(${JSON.stringify(path.join(repo,'listhammer.js'))}).syncStats=async()=>null;
    require(${JSON.stringify(path.join(repo,'youtube/auth.js'))}).Auth.prototype.token=async()=>{throw Error('Simulated OAuth failure');};
  `);
  const child=spawn(process.execPath,['--require',preload,path.join(repo,'server.js')],{env:{...process.env,PORT:'0',OVERLAY_DATA_DIR:directory,YOUTUBE_CHAT_TTS_ENABLED:'true'},stdio:['ignore','pipe','pipe']});
  t.after(async()=>{if(child.exitCode===null){child.kill();await once(child,'exit');}await fs.rm(directory,{recursive:true,force:true});});
  let output='', errors='';
  child.stderr.on('data',c=>{errors+=c;});
  const port=await new Promise((resolve,reject)=>{
    child.stdout.on('data',c=>{output+=c;const m=/TEST_PORT=(\d+)/.exec(output);if(m)resolve(m[1]);});
    child.on('error',reject);child.on('exit',code=>reject(new Error('Server exited '+code+'\n'+errors)));
  });
  const base='http://127.0.0.1:'+port;
  assert.deepEqual(await (await fetch(base+'/remote-lists')).json(),{enabled:false});
  assert.equal((await fetch(base+'/remote-lists/sync',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'})).status,404);
  const registry=await (await fetch(base+'/factions.json')).json();
  assert.deepEqual(registry,require('../public/factions.json'));
  assert.equal(Object.values(registry).flat().filter(n=>n!=='Custom').length,28);
  const stream=await fetch(base+'/toasts/events',{signal:AbortSignal.timeout(10000)});
  const reader=stream.body.getReader();t.after(()=>reader.cancel().catch(()=>{}));
  await reader.read();
  const post=(route,body={})=>fetch(base+route,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  const text='Texto <img src=x onerror=alert(1)> — ¿Sabías qué?';
  const sent=await (await post('/toasts/message',{text})).json();
  assert.equal(sent.toast.text,text);assert.ok(sent.toast.remainingMs > 0 && sent.toast.remainingMs <= 15000);
  let event='';while(!event.includes(text))event+=Buffer.from((await reader.read()).value).toString('utf8');
  assert.ok(event.includes('event: toast'));assert.ok(event.includes(sent.toast.token));
  assert.equal((await post('/toasts/message',{text:'x'.repeat(281)})).status,400);
  assert.equal((await post('/toasts/config',{enabled:'yes'})).status,400);
  const a=await (await post('/toasts/next')).json();const b=await (await post('/toasts/next')).json();assert.notEqual(a.toast.id,b.toast.id);
  const state=await (await fetch(base+'/toasts/state')).json();assert.equal(state.remaining,state.total-2);
  const disk=JSON.parse(await fs.readFile(path.join(directory,'toast-session.json'),'utf8'));assert.equal(disk.seen.length,2);
  assert.equal((await fetch(base+'/toasts/message')).status,405);
  await post('/toasts/reset');assert.equal((await (await fetch(base+'/toasts/state')).json()).remaining,state.total);
  // Layout changes persist as one unit and reach already-connected OBS clients.
  const layoutStream=await fetch(base+'/events',{signal:AbortSignal.timeout(10000)});
  const layoutReader=layoutStream.body.getReader();t.after(()=>layoutReader.cancel().catch(()=>{}));
  await layoutReader.read();
  const layout={title:'Mesa 1',roundHalf:'bottom',left:{name:'Ana',appName:'alpha',faction:'Orks',formation:'Take and Hold',detachments:['Uno','Dos']},right:{name:'Luis',appName:'beta',faction:'Necrons',formation:'Reconnaissance',detachments:['Tres']}};
  const initialLayout=await (await fetch(base+'/state')).json();
  layout.left.rosterId=initialLayout.left.rosterId;layout.right.rosterId=initialLayout.right.rosterId;
  const swapped=require('../public/match-view').swapPlayers(layout);
  assert.equal((await post('/state',swapped)).status,200);
  const frame=Buffer.from((await layoutReader.read()).value).toString('utf8');
  assert.deepEqual(JSON.parse(frame.match(/data: (.*)/)[1]),swapped);
  assert.deepEqual(await (await fetch(base+'/state')).json(),swapped);
  assert.deepEqual(JSON.parse(await fs.readFile(path.join(directory,'overlay-state.json'),'utf8')),swapped);
  const rosterStream=await fetch(base+'/rosters/events',{signal:AbortSignal.timeout(10000)});
  const rosterReader=rosterStream.body.getReader();t.after(()=>rosterReader.cancel().catch(()=>{}));await rosterReader.read();
  const units=[{id:'unit-a',name:'<script>Unidad</script>',enhancement:'Mejora',characters:['Capitán','Teniente'],notes:'Nota',battleshocked:true,deepStrike:true,destroyed:false},{id:'unit-b',name:'Tanque',enhancement:'',characters:[],notes:'',deepStrike:false,destroyed:true}];
  const id=swapped.left.rosterId;
  const roster=await (await post('/rosters/'+id,{revision:0,name:'Cábala de cristal',units,backgroundUrl:'https://example.com/background.png'})).json();assert.equal(roster.revision,1);assert.equal(roster.backgroundUrl,'https://example.com/background.png');
  const rosterEvent=Buffer.from((await rosterReader.read()).value).toString();assert.ok(rosterEvent.includes('unit-a'));
  assert.equal((await post('/rosters/'+id,{revision:0,units:[]})).status,409);
  assert.equal((await post('/rosters/'+id,{revision:1,units:[{...units[0],name:''}]})).status,400);
  assert.equal((await post('/rosters/unknown',{revision:0,units:[]})).status,404);
  const reordered=await (await post('/rosters/'+id,{revision:1,units:[units[1],units[0]]})).json();
  assert.equal(reordered.name,'Cábala de cristal');assert.equal(reordered.units[1].battleshocked,true);
  assert.equal(reordered.backgroundUrl,'https://example.com/background.png');
  assert.equal((await post('/rosters/'+id,{revision:2,units,backgroundUrl:'javascript:alert(1)'})).status,400);
  assert.deepEqual(reordered.units.map(u=>u.id),['unit-b','unit-a']);
  const savedRosters=JSON.parse(await fs.readFile(path.join(directory,'rosters.json'),'utf8'));assert.deepEqual(savedRosters[id],reordered);
  await post('/state',layout); // Swap back: roster identity follows the same player.
  const linked=await (await fetch(base+'/rosters')).json();assert.equal(linked.players.right.rosterId,id);assert.deepEqual(linked.rosters[id].units,reordered.units);
  const patch=(unit,body)=>fetch(base+'/rosters/'+id+'/units/'+unit+'/status',{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  const changed=await (await patch('unit-a',{battleshocked:false,destroyed:true})).json();
  assert.equal(changed.revision,3);assert.equal(changed.units[1].battleshocked,false);assert.equal(changed.units[1].deepStrike,true);assert.equal(changed.units[1].destroyed,true);assert.deepEqual(changed.units[0],reordered.units[0]);assert.equal(changed.name,reordered.name);
  assert.deepEqual(JSON.parse(await fs.readFile(path.join(directory,'rosters.json'),'utf8'))[id],changed);
  assert.equal((await patch('missing',{destroyed:true})).status,404);assert.equal((await patch('unit-a',{name:'overwrite'})).status,400);
  assert.equal((await post('/rosters/'+id,{revision:2,units:[]})).status,409);
  await post('/state',swapped);
  await post('/game/reset');
  const reset=await (await fetch(base+'/state')).json();
  assert.equal(reset.roundHalf,'');assert.deepEqual(reset.left,swapped.left);assert.deepEqual(reset.right,swapped.right);

});
